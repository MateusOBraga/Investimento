"""
glossary.py
Explicações simples dos principais termos usados na análise, pensadas para
quem está começando a investir agora.
"""

GLOSSARIO = {
    "P/L (Preço/Lucro)": (
        "Mostra quantos anos de lucro atual seriam necessários para 'pagar' o "
        "preço da ação. Quanto menor, em geral, mais barata a ação parece — mas "
        "sempre compare com empresas do mesmo setor."
    ),
    "Dividend Yield": (
        "Percentual do preço da ação que a empresa devolveu aos acionistas em "
        "dividendos nos últimos 12 meses. Quanto maior, mais a ação 'paga' para "
        "você continuar com ela."
    ),
    "ROE (Retorno sobre o Patrimônio)": (
        "Mede quanto lucro a empresa gera para cada real de patrimônio que ela "
        "tem. Um ROE alto costuma indicar uma empresa eficiente em gerar retorno."
    ),
    "P/VP (Preço/Valor Patrimonial)": (
        "Compara o preço da ação com o valor contábil da empresa. Abaixo de 1 "
        "pode indicar ação descontada, mas também pode ser sinal de problemas."
    ),
    "Margem Líquida": (
        "Percentual da receita que vira lucro depois de todos os custos e "
        "despesas. Quanto maior, mais eficiente é a empresa em transformar "
        "vendas em lucro."
    ),
    "Dívida/Patrimônio": (
        "Mostra o quanto a empresa deve em relação ao que ela tem de "
        "patrimônio. Valores muito altos indicam mais risco financeiro."
    ),
    "RSI (Índice de Força Relativa)": (
        "Indicador técnico de 0 a 100 que mede se uma ação foi muito comprada "
        "ou muito vendida recentemente. Acima de 70 pode indicar 'sobrecompra'; "
        "abaixo de 30, 'sobrevenda'."
    ),
    "MACD": (
        "Indicador técnico que compara duas médias móveis de preço para "
        "identificar mudanças de tendência e a força do movimento."
    ),
    "Bandas de Bollinger": (
        "Um 'corredor' em volta do preço, baseado na volatilidade recente. "
        "Quando o preço toca a banda de baixo, pode estar 'barato' no curto "
        "prazo; na banda de cima, 'caro'."
    ),
    "Média Móvel (SMA)": (
        "Média do preço de fechamento em um número de dias (ex: 20, 50, 200). "
        "Ajuda a suavizar o gráfico e identificar a tendência."
    ),
    "Score Técnico": (
        "Nota de 0 a 100 baseada só no comportamento do preço e do volume "
        "recentes (o que os gráficos mostram)."
    ),
    "Score Fundamental": (
        "Nota de 0 a 100 baseada na saúde financeira da empresa (lucro, "
        "dívida, dividendos etc)."
    ),
    "Score Final": (
        "Combinação do Score Técnico com o Score Fundamental, ponderada pelo "
        "'peso técnico' escolhido nas configurações."
    ),
    "Beta": (
        "Mede o quanto uma ação costuma variar em relação ao mercado como um "
        "todo. Beta acima de 1 = mais volátil que o mercado; abaixo de 1 = "
        "menos volátil."
    ),
    "FII (Fundo de Investimento Imobiliário)": (
        "Um fundo que reúne o dinheiro de vários investidores para comprar "
        "imóveis (galpões, shoppings, escritórios) ou papéis ligados a "
        "imóveis (CRIs). Você compra 'cotas' na bolsa, como se fossem ações, "
        "e recebe mensalmente parte do aluguel ou dos juros que o fundo "
        "receber — geralmente isento de Imposto de Renda para pessoa física."
    ),
    "ETF (Exchange Traded Fund)": (
        "Um fundo negociado na bolsa que replica um índice inteiro (como o "
        "Ibovespa ou o S&P 500), comprando um 'pacote' das ações que compõem "
        "esse índice. Comprando uma cota, você fica exposto a dezenas de "
        "empresas de uma vez só, o que ajuda bastante na diversificação."
    ),
}
